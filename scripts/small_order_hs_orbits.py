#!/usr/bin/env python3
"""Exhaustive enumeration of induced subgraphs of the Hoffman--Singleton
graph HS up to the action of Aut(HS), with a floating-point Phi screen.

1. All automorphisms of the paper's coordinate HS are found by backtracking
   (expected 252000 = 50 * 7!) and each is verified to preserve the edge set.
2. Deleted sets S are generated by an orderly algorithm: S is canonical iff
   its characteristic number  val(S) = sum_{s in S} 2^(49-s)  is maximal in
   its Aut(HS)-orbit.  Removing the largest element s of a canonical set
   S = S' + {s} gives a canonical set.  (If val(gS') > val(S'), let p be the
   most significant bit where they differ, so p is in gS' but not S'; p > s is
   impossible since then gS' would contain S'; if g(s) < p then gS beats S
   at an earlier bit, otherwise gS and S agree above p and gS has bit p.
   Either way val(gS) > val(S).)  So every orbit of k-sets
   has exactly one canonical representative and it is reached from a
   canonical (k-1)-set by adding an element larger than its maximum.
3. The number of canonical k-sets is cross-checked against the Burnside
   (cycle-index) count of Aut(HS)-orbits of k-subsets.
4. For every canonical S with HS - S connected, an exact integer certificate
   of non-strictness is attempted (integer vector x with x^T (qD + pI) x < 0,
   delta* = p/q exact; small_order_core.batch_phi_certified).  For orders
   <= EXACT_MAX_ORDER every connected S without such a certificate is decided
   exactly by Bareiss elimination of qD + pI.  Float Phi is for ranking only.
"""

from __future__ import annotations

import argparse
import json
import os
import sys
import time
from multiprocessing import Pool

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import small_order_core as core  # noqa: E402

N = 50
TOL = 1e-6
EXACT_MAX_ORDER = 38

# ---------------------------------------------------------------------------
# automorphisms
# ---------------------------------------------------------------------------


def automorphisms(a):
    n = a.shape[0]
    nb = [0] * n
    for u in range(n):
        for v in np.flatnonzero(a[u]).tolist():
            nb[u] |= 1 << v
    # Constraint-first order: 0, its neighbours, then repeatedly the vertex
    # with the most already-ordered neighbours (keeps the backtracking almost
    # branch-free once the images of 0 and N(0) are fixed).
    order = [0] + np.flatnonzero(a[0]).tolist()
    seen = set(order)
    while len(order) < n:
        best = max((v for v in range(n) if v not in seen),
                   key=lambda v: (sum(1 for w in order if a[v, w]), -v))
        order.append(best)
        seen.add(best)
    pos = {v: i for i, v in enumerate(order)}
    earlier_nbrs = [[w for w in np.flatnonzero(a[v]).tolist() if pos[w] < pos[v]] for v in order]
    results = []
    phi = [-1] * n

    def rec(i, used):
        if i == n:
            results.append(list(phi))
            return
        v = order[i]
        en = earlier_nbrs[i]
        want = 0
        for w in en:
            want |= 1 << phi[w]
        if en:
            cands = nb[phi[en[0]]] & ~used
        else:
            cands = ((1 << n) - 1) & ~used
        while cands:
            low = cands & -cands
            c = low.bit_length() - 1
            cands ^= low
            if (nb[c] & used) == want:
                phi[v] = c
                rec(i + 1, used | low)
                phi[v] = -1

    rec(0, 0)
    perm = np.array(results, dtype=np.int64)
    # verify
    us, vs = np.nonzero(np.triu(a))
    assert a[perm[:, us], perm[:, vs]].all(), "non-automorphism found"
    assert len({tuple(p) for p in perm.tolist()}) == len(perm)
    return perm


def burnside_counts(perm):
    """Number of orbits of k-subsets for k=0..N via the cycle index."""
    from fractions import Fraction
    from collections import Counter
    types = Counter()
    for p in perm.tolist():
        seen = [False] * len(p)
        lens = []
        for i in range(len(p)):
            if not seen[i]:
                L = 0
                j = i
                while not seen[j]:
                    seen[j] = True
                    j = p[j]
                    L += 1
                lens.append(L)
        types[tuple(sorted(lens))] += 1
    total = [0] * (len(perm[0]) + 1)
    for lens, mult in types.items():
        poly = [1]
        for L in lens:
            new = [0] * (len(poly) + L)
            for i, c in enumerate(poly):
                new[i] += c
                new[i + L] += c
            poly = new
        for k, c in enumerate(poly):
            total[k] += mult * c
    g = len(perm)
    out = []
    for t in total:
        assert t % g == 0
        out.append(t // g)
    return out, {str(k): v for k, v in types.items()}


# ---------------------------------------------------------------------------
# orderly generation
# ---------------------------------------------------------------------------

W = None
HS = None
MAXDEPTH = None


def set_globals(perm, maxdepth):
    """Set module globals; worker processes inherit them by fork (Linux)."""
    global W, HS, MAXDEPTH
    HS = core.hoffman_singleton()
    W = (np.uint64(1) << (np.uint64(N - 1) - perm.astype(np.uint64))).astype(np.uint64)
    MAXDEPTH = maxdepth


def load_or_compute_automorphisms(cache):
    hs = core.hoffman_singleton()
    if cache and os.path.exists(cache):
        perm = np.load(cache)
        us, vs = np.nonzero(np.triu(hs))
        assert hs[perm[:, us], perm[:, vs]].all()
        assert len(np.unique(perm, axis=0)) == len(perm)
        return perm
    perm = automorphisms(hs)
    if cache:
        np.save(cache, perm)
    return perm


def val(s):
    return sum(1 << (N - 1 - x) for x in s)


def children(t, vt):
    """Canonical children of canonical set t (sorted list) with image-value
    vector vt (shape (|G|,), uint64).  Returns list of (s_tuple, vs)."""
    start = (t[-1] + 1) if t else 0
    if start >= N:
        return []
    cand = np.arange(start, N)
    m = vt[:, None] + W[:, cand]
    mx = m.max(axis=0)
    base = val(t)
    out = []
    for j, c in enumerate(cand.tolist()):
        v = base + (1 << (N - 1 - c))
        if int(mx[j]) <= v:
            out.append(c)
    return out


class Collector:
    def __init__(self):
        self.count = {}
        self.top = {}
        self.hits = {}
        self.buf = {}

    def add(self, s):
        k = len(s)
        self.buf.setdefault(k, []).append(s)
        if len(self.buf[k]) >= 2000:
            self.flush(k)

    def flush(self, k):
        sets = self.buf.get(k)
        if not sets:
            return
        self.buf[k] = []
        arr = np.array(sets, dtype=np.int64)
        b = len(sets)
        mask = np.ones((b, N), dtype=bool)
        mask[np.arange(b)[:, None], arr] = False
        keep = np.nonzero(mask)[1].reshape(b, N - k)
        sub = HS[keep[:, :, None], keep[:, None, :]]
        phi, ds, lam, diam, cert, Q, p, q = core.batch_phi_certified(sub)
        self.count[k] = self.count.get(k, 0) + b
        fin = np.isfinite(phi)
        order = np.argsort(-phi)[:20]
        cur = self.top.get(k, [])
        cur = cur + [(float(phi[i]), float(ds[i]), float(lam[i]), float(diam[i]), sets[i]) for i in order if fin[i]]
        self.top[k] = sorted(cur, key=lambda z: -z[0])[:20]
        h = self.hits.setdefault(k, {"n": 0, "connected": 0, "certified": 0, "uncertified": 0, "sets": []})
        h["n"] += int((phi > -TOL).sum())
        h["connected"] += int(fin.sum())
        h["certified"] += int(cert.sum())
        unc = np.flatnonzero(fin & ~cert).tolist()
        h["uncertified"] += len(unc)
        if N - k <= EXACT_MAX_ORDER:
            h["sets"].extend(sets[i] for i in unc)

    def flush_all(self):
        for k in list(self.buf):
            self.flush(k)


def dfs_task(root):
    """Enumerate all canonical descendants of canonical set `root` (excluding
    root itself) down to MAXDEPTH, evaluating Phi for each."""
    col = Collector()
    t = list(root)
    vt = W[:, t].sum(axis=1) if t else np.zeros(W.shape[0], dtype=np.uint64)
    stack = [(t, vt)]
    while stack:
        t, vt = stack.pop()
        if len(t) >= MAXDEPTH:
            continue
        for c in children(t, vt):
            s = t + [c]
            col.add(s)
            if len(s) < MAXDEPTH:
                stack.append((s, vt + W[:, c]))
    col.flush_all()
    return col.count, col.top, col.hits


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--maxdepth", type=int, default=13)
    ap.add_argument("--rootdepth", type=int, default=7)
    ap.add_argument("--workers", type=int, default=8)
    ap.add_argument("--out", required=True)
    ap.add_argument("--cache", default="")
    ap.add_argument("--exact-max-order", type=int, default=38,
                    help="decide every uncertified connected set exactly (Bareiss) at orders <= this")
    args = ap.parse_args()
    global EXACT_MAX_ORDER
    EXACT_MAX_ORDER = args.exact_max_order
    t0 = time.time()
    hs = core.hoffman_singleton()
    perm = load_or_compute_automorphisms(args.cache)
    print("automorphisms:", len(perm), "time %.1fs" % (time.time() - t0), flush=True)
    assert len(perm) == 252000
    burn, types = burnside_counts(perm)
    print("burnside orbit counts k=0..20:", burn[:21], flush=True)
    set_globals(perm, args.maxdepth)
    # sequential BFS to rootdepth
    level = [[]]
    allroots = []
    main_col = Collector()
    for d in range(1, args.rootdepth + 1):
        nxt = []
        for t in level:
            vt = W[:, t].sum(axis=1) if t else np.zeros(W.shape[0], dtype=np.uint64)
            for c in children(t, vt):
                nxt.append(t + [c])
        level = nxt
        for s in level:
            main_col.add(s)
        print("level %d canonical %d (burnside %d)" % (d, len(level), burn[d]), flush=True)
        assert len(level) == burn[d]
    main_col.flush_all()
    roots = level
    count = dict(main_col.count)
    top = dict(main_col.top)
    hits = {k: dict(v) for k, v in main_col.hits.items()}
    done = 0
    with Pool(args.workers) as pool:
        for c, tp, h in pool.imap_unordered(dfs_task, roots, chunksize=1):
            done += 1
            for k, v in c.items():
                count[k] = count.get(k, 0) + v
            for k, v in tp.items():
                top[k] = sorted(top.get(k, []) + v, key=lambda z: -z[0])[:20]
            for k, v in h.items():
                hh = hits.setdefault(k, {"n": 0, "connected": 0, "certified": 0, "uncertified": 0, "sets": []})
                for key2 in ("n", "connected", "certified", "uncertified"):
                    hh[key2] += v[key2]
                hh["sets"].extend(v["sets"])
            if done % 50 == 0:
                print("roots done %d/%d  %.0fs  counts %s" % (done, len(roots), time.time() - t0,
                      {k: count[k] for k in sorted(count)}), flush=True)
    levels = []
    for k in sorted(count):
        exact = []
        for s in hits.get(k, {}).get("sets", []):
            keep = [v for v in range(N) if v not in set(s)]
            cert = core.exact_certificate(core.induced(hs, keep))
            cert["deleted_HS_indices"] = s
            cert["deleted_HS_labels"] = [core.hs_label(v) for v in s]
            exact.append(cert)
        levels.append({
            "k_deleted": k,
            "order": N - k,
            "canonical_sets": count[k],
            "burnside_orbits": burn[k],
            "count_matches_burnside": count[k] == burn[k],
            "connected": hits.get(k, {}).get("connected"),
            "float_phi_gt_minus_tol": hits.get(k, {}).get("n"),
            "certified_nonstrict_integer_vector": hits.get(k, {}).get("certified"),
            "uncertified_connected": hits.get(k, {}).get("uncertified"),
            "max_float_phi": top[k][0][0] if top.get(k) else None,
            "top20": [{"phi": z[0], "delta_star": z[1], "lambda_min": z[2], "diameter": z[3],
                       "deleted": z[4], "deleted_labels": [core.hs_label(v) for v in z[4]]} for z in top.get(k, [])],
            "exact_certificates": exact,
            "exact_strict": sum(1 for c in exact if c.get("strict")),
            "exact_nonstrict_by_bareiss": sum(1 for c in exact if not c.get("strict")),
            "all_connected_decided_exactly": (N - k <= EXACT_MAX_ORDER and
                                              hits.get(k, {}).get("certified", 0) + len(exact)
                                              == hits.get(k, {}).get("connected")),
        })
        L = levels[-1]
        print("k=%d order=%d canonical=%d burnside=%d connected=%s certified_nonstrict=%s uncertified=%s "
              "exact_strict=%d exact_nonstrict=%d decided=%s maxphi=%s" % (
                  k, N - k, count[k], burn[k], L["connected"], L["certified_nonstrict_integer_vector"],
                  L["uncertified_connected"], L["exact_strict"], L["exact_nonstrict_by_bareiss"],
                  L["all_connected_decided_exactly"], L["max_float_phi"]), flush=True)
    out = {
        "automorphism_count": len(perm),
        "burnside_orbit_counts": burn,
        "maxdepth": args.maxdepth,
        "seconds": time.time() - t0,
        "levels": levels,
    }
    with open(args.out, "w") as fh:
        json.dump(out, fh, indent=1)
    print("DONE %.0fs" % (time.time() - t0))


if __name__ == "__main__":
    main()
